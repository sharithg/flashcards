import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const results=[];
const base='http://127.0.0.1:3000';
const go=async path=>{await page.goto(base+path,{waitUntil:'domcontentloaded'});await page.waitForTimeout(400);};
const snap=async name=>{await page.waitForTimeout(250);await page.screenshot({path:`ui-review/artifacts/${name}.png`,fullPage:true});results.push({name,text:await page.locator('body').innerText()});};
try {
  await go('/');
  await page.getByPlaceholder('Search sets and terms').fill('mitochondria');
  results.push({name:'search-by-term',text:await page.locator('main').innerText()});
  await page.getByPlaceholder('Search sets and terms').fill('no-such-term');
  await snap('mobile-search-empty');
  await go('/sets/spanish-basics/flashcards');
  await page.locator('body').click({position:{x:10,y:700}});
  await page.keyboard.press('Space');
  await page.waitForTimeout(400);
  results.push({name:'space-flip',text:await page.locator('main').innerText()});
  await page.keyboard.press('ArrowRight');
  results.push({name:'arrow-next',text:await page.locator('main').innerText()});
  await go('/sets/spanish-basics/learn');
  await page.getByRole('button',{name:'Start learning',exact:true}).click();
  await snap('mobile-learn-active');
  const options=page.locator('main button');
  results.push({name:'learn-buttons',buttons:await options.allTextContents()});
  await options.first().click();
  await snap('mobile-learn-feedback');
  await go('/sets/spanish-basics/match');
  await page.getByRole('button',{name:'Start game',exact:true}).click();
  await snap('mobile-match-active');
  await go('/sets/spanish-basics/test');
  await page.getByRole('button',{name:'Start test',exact:true}).click();
  await snap('mobile-test-active');
  await go('/create');
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await snap('mobile-create-validation');
  await page.getByRole('button',{name:'Import',exact:true}).click();
  await snap('mobile-import');
  await page.emulateMedia({colorScheme:'dark'});
  await go('/');
  await snap('mobile-library-dark');
  await page.setViewportSize({width:320,height:720});
  await go('/sets/spanish-basics/flashcards');
  await snap('narrow-flashcards');
  results.push({name:'320px-overflow',value:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)});
} finally {await writeFile('ui-review/artifacts/interactions.json',JSON.stringify(results,null,2));await browser.close();}
